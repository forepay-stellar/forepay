#!/usr/bin/env python3
"""Regenerate tools/fixtures/forepay-claim.json, the cross-language claim vector (#76).

The fixture is what proves `sc/advance/src/claim.rs` rebuilds the exact bytes an attestor
signed. It has to be regenerated whenever the claim encoding changes, and it was wrong to
have it as a hand-pasted blob the first time: when #76 changed the encoding, nobody could
re-derive it. This script is the derivation.

    python3 tools/make_claim_fixture.py          # write the fixture
    python3 tools/make_claim_fixture.py --check  # fail if the file is out of date

The signing key is a **test constant**, not a secret: the fixture's whole purpose is that
anyone can reproduce it, and the key it is signed with is public by construction. The real
attestor's signature is in tools/fixtures/real-reclaim-proof.json, which this never
replaces — that one proves the digest chain against Reclaim's own production key.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import secp256k1_probe as secp  # noqa: E402

HERE = Path(__file__).parent
OUT = HERE / "fixtures" / "forepay-claim.json"

# A published test key. Same constant tools/rehearsal.py signs its probe proofs with.
TEST_KEY = 0x1111111111111111111111111111111111111111111111111111111111111111

BORROWER = "GA2CD6PMHMBTCFAQDO3R22BSZN5ZSVTAKVNOKXL2SONZBLGRAYIOWWH2"
CONTEXT_MESSAGE = "Forepay advance request"
PUB_ID = "pub-1234567890123456"
WINDOW_START = "2026-07-01"
WINDOW_END = "2026-09-30"
REVENUE = "1234.56"
PROVIDER_HASH = "0x569b93233185c054ed9fda68b5aef8fda180b6d291180450bf757b11bb52f7df"
TIMESTAMP_S = 1_760_000_000
EPOCH = 1

# The attestor's `owner` in a real claim is the Reclaim app the relay proves with, not the
# borrower (#102). This is Forepay's app id, which every real claim carries in public. The
# fixture is signed twice: once with this owner, as a real attestor signs, and once with
# the borrower as owner, which is what the contract rebuilt before #102 and what the
# rehearsal's test witness still signs for a contract with no owner pinned.
APP_OWNER = "0x6415200c713135e77157e1536d488df4f2bb7d04"

# The literal segments of the request, with the seven values interleaved between them.
# The query is the one be/src/adsense/request.ts actually builds (#4, #74): AdSense takes
# each date as three unpadded integers, because `startDate` is an `object (Date)` and the
# REST transport flattens it. There is no string date form to use instead.
TEMPLATE = [
    '{"method":"GET","url":"https://adsense.googleapis.com/v2/accounts/',
    "/reports:generate?dateRange=CUSTOM&startDate.year=",
    "&startDate.month=",
    "&startDate.day=",
    "&endDate.year=",
    "&endDate.month=",
    "&endDate.day=",
    '&metrics=ESTIMATED_EARNINGS&currencyCode=USD&reportingTimeZone=ACCOUNT_TIME_ZONE"}',
]


def unpadded(digits: str) -> str:
    """ASCII digits as an integer is serialised: "07" -> "7", "00" -> "0"."""
    return str(int(digits))


def date_values(date: str) -> list[str]:
    y, m, d = date.split("-")
    return [unpadded(y), unpadded(m), unpadded(d)]


def build() -> dict:
    values = [PUB_ID] + date_values(WINDOW_START) + date_values(WINDOW_END)
    assert len(TEMPLATE) == len(values) + 1, "a template of N parts takes N-1 values"

    parameters = TEMPLATE[0]
    for i, value in enumerate(values):
        parameters += value + TEMPLATE[i + 1]

    context = (
        '{"contextAddress":"' + BORROWER
        + '","contextMessage":"' + CONTEXT_MESSAGE
        + '","extractedParameters":{"revenueUsd":"' + REVENUE
        + '"},"providerHash":"' + PROVIDER_HASH + '"}'
    )

    identifier = "0x" + secp.keccak256(
        b"http\n" + parameters.encode() + b"\n" + context.encode()
    ).hex()
    sign_data = f"{identifier}\n{BORROWER.lower()}\n{TIMESTAMP_S}\n{EPOCH}"
    digest = secp.eip191_digest(sign_data)
    r, s, rec = secp.sign(digest, TEST_KEY)

    app_sign_data = f"{identifier}\n{APP_OWNER.lower()}\n{TIMESTAMP_S}\n{EPOCH}"
    app_r, app_s, app_rec = secp.sign(secp.eip191_digest(app_sign_data), TEST_KEY)

    return {
        "_source": (
            "Generated by tools/make_claim_fixture.py. Signed with a published test key, "
            "not an attestor key — the real attestor vector is real-reclaim-proof.json."
        ),
        "borrower": BORROWER,
        "contextMessage": CONTEXT_MESSAGE,
        "pubId": PUB_ID,
        "windowStart": WINDOW_START,
        "windowEnd": WINDOW_END,
        "revenueUsd": REVENUE,
        "providerHash": PROVIDER_HASH,
        "templateParts": TEMPLATE,
        "values": values,
        "timestampS": TIMESTAMP_S,
        "epoch": EPOCH,
        "parameters": parameters,
        "context": context,
        "identifier": identifier,
        "signData": sign_data,
        "messageDigest": digest.hex(),
        "signature64": (r.to_bytes(32, "big") + s.to_bytes(32, "big")).hex(),
        "recoveryId": rec,
        "signerAddress": secp.address_of(TEST_KEY).hex(),
        "appOwner": APP_OWNER,
        "appOwnerSignData": app_sign_data,
        "appOwnerSignature64": (app_r.to_bytes(32, "big") + app_s.to_bytes(32, "big")).hex(),
        "appOwnerRecoveryId": app_rec,
        # The same claim chain for AdMob (#94): a different host, the window inside a
        # signed POST body, the figure in micros under its own key, and therefore a
        # different value order. Signed with the app as owner, because that is the only
        # shape a real attestor produces.
        "admob": build_admob(),
    }


# ---------------------------------------------------------------- AdMob (#94)

ADMOB_PUB_ID = "pub-1234567890123456"
ADMOB_REVENUE_MICROS = "12345678"          # $12.345678 -> 1234 cents, truncated
ADMOB_PROVIDER_HASH = "0x" + "cd" * 32

# The AdMob request the relay builds, as the attestor canonicalises it: keys sorted, so
# `body` comes before `url`. That ordering is the whole reason AdMob needs its own value
# order — the window lives in `body` and the publisher id in `url`, so the dates come
# first and `pub_id` last (#93).
#
# Built here rather than pasted, so the escaping is produced by the same json encoder the
# relay uses instead of being typed by hand. `tools/fixtures/admob-claim.json` (#101) is
# the relay's own copy of the same request; this one exists so the contract has a *signed*
# AdMob claim to verify, which that one has no signature for.
ADMOB_MATCH = (
    r'"row":\s*\{\s*"metricValues":\s*\{\s*"ESTIMATED_EARNINGS":'
    r'\s*\{\s*"microsValue":\s*"(?<revenueMicros>\d+)"\s*\}\s*\}\s*\}'
)
ADMOB_CURRENCY_MATCH = r'"localizationSettings":\s*\{\s*"currencyCode":\s*"USD"\s*\}'


def admob_body(start: str, end: str) -> str:
    sy, sm, sd = date_values(start)
    ey, em, ed = date_values(end)
    return (
        '{"reportSpec":{"dateRange":{"startDate":{"year":' + sy
        + ',"month":' + sm + ',"day":' + sd
        + '},"endDate":{"year":' + ey + ',"month":' + em + ',"day":' + ed
        + '}},"metrics":["ESTIMATED_EARNINGS"],"localizationSettings":{"currencyCode":"USD"}}}'
    )


def admob_parameters(pub_id: str, start: str, end: str) -> str:
    """The canonical signed parameters: keys in sorted order, body as a JSON string."""
    return json.dumps(
        {
            "body": admob_body(start, end),
            "headers": {
                "User-Agent": "reclaim/0.0.1",
                "accept": "application/json",
                "content-type": "application/json",
            },
            "method": "POST",
            "responseMatches": [
                {"type": "regex", "value": ADMOB_CURRENCY_MATCH},
                {"type": "regex", "value": ADMOB_MATCH},
            ],
            "responseRedactions": [
                {"regex": ADMOB_CURRENCY_MATCH},
                {"regex": ADMOB_MATCH},
            ],
            "url": f"https://admob.googleapis.com/v1/accounts/{pub_id}/networkReport:generate",
        },
        separators=(",", ":"),
        sort_keys=True,
    )


def admob_template(parameters: str, values: list[str]) -> list[str]:
    """Split `parameters` at the seven values, left to right, and prove the split.

    The same three proofs `tools/pin_template.py` applies, because a template derived
    without them round-trips happily while being wrong: a split at the wrong occurrence
    of a one-character value like "1" or "7" reproduces the string and then fails for
    every other window.
    """
    parts: list[str] = []
    cursor = 0
    for i, value in enumerate(values):
        at = parameters.find(value, cursor)
        assert at >= 0, f"value {i} ({value!r}) not found after offset {cursor}"
        parts.append(parameters[cursor:at])
        cursor = at + len(value)
    parts.append(parameters[cursor:])

    rebuilt = parts[0]
    for i, value in enumerate(values):
        rebuilt += value + parts[i + 1]
    assert rebuilt == parameters, "the parts and values do not reproduce the parameters"

    # Structure, which is what actually catches a wrong occurrence. Each date value sits
    # immediately after its own escaped JSON key, and the publisher id after /accounts/.
    expected_tails = [
        r'\"year\":', r'\"month\":', r'\"day\":',
        r'\"year\":', r'\"month\":', r'\"day\":',
        "/accounts/",
    ]
    for i, tail in enumerate(expected_tails):
        assert parts[i].endswith(tail), f"part {i} should end {tail!r}, ends {parts[i][-14:]!r}"
    assert len(parts) == 8, f"{len(parts)} parts, want 8"
    return parts


def build_admob() -> dict:
    values = date_values(WINDOW_START) + date_values(WINDOW_END) + [ADMOB_PUB_ID]
    parameters = admob_parameters(ADMOB_PUB_ID, WINDOW_START, WINDOW_END)
    parts = admob_template(parameters, values)

    context = (
        '{"contextAddress":"' + BORROWER
        + '","contextMessage":"' + CONTEXT_MESSAGE
        + '","extractedParameters":{"revenueMicros":"' + ADMOB_REVENUE_MICROS
        + '"},"providerHash":"' + ADMOB_PROVIDER_HASH + '"}'
    )
    identifier = "0x" + secp.keccak256(
        b"http\n" + parameters.encode() + b"\n" + context.encode()
    ).hex()
    sign_data = f"{identifier}\n{APP_OWNER.lower()}\n{TIMESTAMP_S}\n{EPOCH}"
    r, s, rec = secp.sign(secp.eip191_digest(sign_data), TEST_KEY)

    return {
        "pubId": ADMOB_PUB_ID,
        "revenueMicros": ADMOB_REVENUE_MICROS,
        "providerHash": ADMOB_PROVIDER_HASH,
        "templateParts": parts,
        "values": values,
        "parameters": parameters,
        "context": context,
        "identifier": identifier,
        "signData": sign_data,
        "signature64": (r.to_bytes(32, "big") + s.to_bytes(32, "big")).hex(),
        "recoveryId": rec,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the fixture is stale")
    a = ap.parse_args()

    fixture = json.dumps(build(), indent=2) + "\n"
    if a.check:
        if not OUT.exists() or OUT.read_text() != fixture:
            print(f"{OUT} is out of date; run tools/make_claim_fixture.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0

    OUT.write_text(fixture)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

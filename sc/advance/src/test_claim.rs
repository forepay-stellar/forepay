//! Forepay #9 — the contract rebuilds the exact bytes an attestor signed.
//!
//! # Why the mock verifier does real cryptography
//!
//! A mock that returns `Ok(())` would prove the plumbing and nothing else. This one runs
//! `secp256k1_recover` on whatever digest the contract hands it and checks the recovered
//! address against a known signer — exactly what Reclaim's deployed contract does. So if
//! the contract builds the digest wrongly by one byte, recovery yields a different address
//! and the test fails, which is the only property worth testing here.
//!
//! The fixture is generated by `tools/make_claim_fixture.py`, which signs with
//! `tools/secp256k1_probe.py` — the implementation proven in #3 against a **real
//! production-attestor signature** accepted on chain. So the chain of trust is: real
//! attestor → Python reference → this fixture → the contract.
//!
//! Regenerate it with `python3 tools/make_claim_fixture.py` whenever the claim encoding
//! changes, and copy the new `signature64` and `signerAddress` into the constants below.
//! `--check` fails if the committed fixture no longer matches the script, so the two
//! cannot drift apart silently the way they did before #76.


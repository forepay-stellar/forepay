/**
 * Forepay #96: `tools/fixtures/admob-claim.json`, which `tools/pin_template.py --self-test`
 * derives the AdMob template from, is the request this relay actually builds. If the
 * request changes, this fails, and the fixture has to be regenerated with the change,
 * so the Python derivation is never proven against bytes the relay no longer sends.
 *
 * Regenerate: ADMOB_FIXTURE=write pnpm -C be test
 */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

import { CONTEXT_MESSAGE } from "../adsense/request.js";
import { canonicalStringify, getIdentifierFromClaimInfo } from "../reclaim/claim-digest.js";
import { FIGURE, buildAdmobRequest } from "./request.js";

const FILE = join(import.meta.dirname, "..", "..", "..", "tools", "fixtures", "admob-claim.json");

function build() {
  const pubId = "pub-1234567890123456";
  const borrower = "GA2CD6PMHMBTCFAQDO3R22BSZN5ZSVTAKVNOKXL2SONZBLGRAYIOWWH2";
  const window = { start: { year: 2026, month: 7, day: 1 }, end: { year: 2026, month: 9, day: 30 } };
  const req = buildAdmobRequest({ publisherId: pubId, stellarAddress: borrower, window });
  // The attestor adds its User-Agent and sorts the keys, as the #93 spike proof showed.
  const parameters = canonicalStringify({
    body: req.options.body,
    headers: { "User-Agent": "reclaim/0.0.1", ...req.options.headers },
    method: req.options.method,
    responseMatches: req.secretOptions.responseMatches,
    responseRedactions: req.secretOptions.responseRedactions,
    url: req.url,
  });
  const context = JSON.stringify({
    contextAddress: borrower,
    contextMessage: CONTEXT_MESSAGE,
    extractedParameters: { [FIGURE]: "12345678" },
    providerHash: `0x${"cd".repeat(32)}`,
  });
  return {
    _source: "Generated by be/src/admob/fixture.test.ts from the relay's own AdMob request. Made-up account, window and figure.",
    pubId,
    windowStart: "2026-07-01",
    windowEnd: "2026-09-30",
    parameters,
    context,
    identifier: getIdentifierFromClaimInfo({ provider: "http", parameters, context }),
  };
}

test("the AdMob template fixture is the request the relay builds", () => {
  const want = JSON.stringify(build(), null, 2) + "\n";
  if (process.env.ADMOB_FIXTURE === "write") writeFileSync(FILE, want);
  assert.equal(readFileSync(FILE, "utf8"), want, "tools/fixtures/admob-claim.json is stale; regenerate it (see the header)");
});
